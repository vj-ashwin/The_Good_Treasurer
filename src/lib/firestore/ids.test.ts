import { describe, expect, it } from 'vitest'
import { isUuid, newId } from './ids'

describe('isUuid', () => {
  it('accepts ids generated by crypto.randomUUID()', () => {
    expect(isUuid(crypto.randomUUID())).toBe(true)
    expect(isUuid('11111111-1111-4111-8111-111111111111')).toBe(true)
  })

  it('rejects anything the rules would reject', () => {
    expect(isUuid('11111111-1111-4111-8111-11111111111')).toBe(false) // too short
    expect(isUuid('11111111111141118111111111111111')).toBe(false) // no hyphens
    expect(isUuid('11111111-1111-4111-8111-11111111111Z')).toBe(false) // not hex
    expect(isUuid('AAAAAAAA-AAAA-4AAA-8AAA-AAAAAAAAAAAA')).toBe(false) // uppercase
    expect(isUuid('{11111111-1111-4111-8111-111111111111}')).toBe(false) // braces
    expect(isUuid(42)).toBe(false)
    expect(isUuid(null)).toBe(false)
  })
})

describe('newId', () => {
  it('mints unique UUIDs', () => {
    const ids = new Set(Array.from({ length: 100 }, () => newId()))
    expect(ids.size).toBe(100)
    for (const id of ids) expect(isUuid(id)).toBe(true)
  })
})
